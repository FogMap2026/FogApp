-- ================================================================
-- V6: 발자취 작성 횟수(users.footprint_quota)
-- 관련 이슈: #116 (발자취 재설계 5.5-3)
--
-- 발자취가 길목마다 붙기 시작하면 도배가 곧바로 문제가 된다. 무제한이면
-- 한 자리에서 수십 개를 쏟아부을 수 있다.
--
-- 단순히 상한만 두면 다 쓴 뒤 아무것도 못 하게 된다. 그래서 스팟을 정복하면
-- 회복시킨다 — "글을 더 남기고 싶으면 더 걸어라"가 되어, 도배 방지와 탐험
-- 유도가 한 장치로 풀린다. 설계 근거는 docs/footprint-redesign.md 3-5 참고.
--
-- 기본값 3: 첫 스팟을 정복하기 전에도 몇 개는 남겨볼 수 있어야 한다.
-- 기존 사용자도 같은 값으로 시작한다(DEFAULT 가 소급 적용된다).
-- ================================================================

ALTER TABLE users
    ADD COLUMN footprint_quota INT NOT NULL DEFAULT 3;

COMMENT ON COLUMN users.footprint_quota IS
    '남은 발자취 작성 횟수(#116). 작성 시 1 감소, 방문 인증 성공 시 기본값으로 리셋.';
